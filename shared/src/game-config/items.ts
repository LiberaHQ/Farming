export type ToolKind = 'axe' | 'pickaxe' | 'hoe' | 'watering_can' | 'fishing_rod' | 'sword';
export type ItemCategory = 'tool' | 'resource' | 'seed' | 'crop' | 'consumable' | 'placeable' | 'animal' | 'fish' | 'food' | 'furniture' | 'equipment' | 'artifact';

export interface ItemDef {
  id: ItemId;
  name: string;
  description: string;
  category: ItemCategory;
  maxStack: number;
  /** Price the merchant pays. Undefined = cannot be sold. */
  sellPrice?: number;
  /** Price at the merchant. Undefined = not sold in the shop. */
  buyPrice?: number;
  tool?: { kind: ToolKind; power: number };
  /** Seeds: the crop they grow. */
  plants?: CropId;
  /** Food: energy restored when eaten. */
  energy?: number;
  /** Rings and armour: worn by using them; one of each slot. */
  equip?: { slot: 'ring' | 'armor'; attack?: number; defense?: number; luck?: boolean };
  /** Food: a timed bonus while it lasts (game minutes). */
  buff?: { kind: BuffKind; minutes: number };
  /** Buildables: what gets placed in the world. */
  places?: PlaceableKind;
  /** Animals: released onto the farm. */
  releases?: 'chicken' | 'duck' | 'rabbit' | 'cow' | 'sheep';
  /** Furniture: goes inside your cottage. */
  furniture?: FurnitureKind;
  /** Shop items that only appear once the player has earned this much in total. */
  unlockAtEarnings?: number;
}

